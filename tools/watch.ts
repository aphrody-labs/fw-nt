#!/usr/bin/env bun
// Active tracking of every upstream of forks.toml plus the most recently pushed repositories of the Microsoft org:
// open issues, open PRs, forks, discussions, stars, latest release, last push, plus the 3 newest issues, PRs and discussions.
// Writes docs/activity/upstreams.tsv, docs/activity/microsoft-recent.tsv and docs/activity/latest.md (stable paths, so
// `git diff` shows what moved). One GraphQL call per batch of 20 repositories.
// Usage: bun tools/watch.ts [--microsoft N]   (default N = 60)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const out = join(root, "docs", "activity");
mkdirSync(out, { recursive: true });
const forks = (Bun.TOML.parse(readFileSync(join(root, "forks.toml"), "utf8")) as { fork: { name: string; upstream: string }[] }).fork;
const nArg = process.argv.indexOf("--microsoft");
const msN = nArg > 0 ? Number(process.argv[nArg + 1]) : 60;

function gh(args: string[]): any {
  const p = Bun.spawnSync(["gh", ...args], { stdout: "pipe", stderr: "pipe" });
  if (p.exitCode !== 0) throw new Error(p.stderr.toString().trim().split("\n").at(-1));
  return JSON.parse(p.stdout.toString());
}

const FIELDS = `nameWithOwner pushedAt stargazerCount forkCount isArchived
  issues(states: OPEN) { totalCount } pullRequests(states: OPEN) { totalCount } discussions { totalCount }
  latestRelease { tagName publishedAt }
  ri: issues(last: 3, states: OPEN) { nodes { number title createdAt } }
  rp: pullRequests(last: 3, states: OPEN) { nodes { number title createdAt } }
  rd: discussions(last: 3) { nodes { number title createdAt } }`;

type Repo = Record<string, any>;
function fetchRepos(names: string[]): Repo[] {
  const res: Repo[] = [];
  for (let i = 0; i < names.length; i += 20) {
    const batch = names.slice(i, i + 20);
    const q = `query { ${batch.map((n, j) => {
      const [o, r] = n.split("/");
      return `r${j}: repository(owner: ${JSON.stringify(o)}, name: ${JSON.stringify(r)}) { ${FIELDS} }`;
    }).join("\n")} }`;
    const d = gh(["api", "graphql", "-f", `query=${q}`]).data;
    for (let j = 0; j < batch.length; j++) if (d[`r${j}`]) res.push(d[`r${j}`]);
  }
  return res;
}

const day = (s?: string) => (s ? s.slice(0, 10) : "-");
const header = "repo\tpushed\tstars\tforks\topen_issues\topen_prs\tdiscussions\tlatest_release\trelease_date\tarchived";
const row = (r: Repo) =>
  [r.nameWithOwner, day(r.pushedAt), r.stargazerCount, r.forkCount, r.issues.totalCount, r.pullRequests.totalCount,
    r.discussions.totalCount, r.latestRelease?.tagName ?? "-", day(r.latestRelease?.publishedAt), r.isArchived].join("\t");

const up = fetchRepos(forks.map((f) => f.upstream)).sort((a, b) => b.pushedAt.localeCompare(a.pushedAt));
writeFileSync(join(out, "upstreams.tsv"), [header, ...up.map(row)].join("\n") + "\n");

const recent = gh(["api", `orgs/microsoft/repos?sort=pushed&direction=desc&per_page=${Math.min(msN, 100)}`]) as { full_name: string; archived: boolean }[];
const ms = fetchRepos(recent.filter((r) => !r.archived).map((r) => r.full_name));
writeFileSync(join(out, "microsoft-recent.tsv"), [header, ...ms.map(row)].join("\n") + "\n");

const items = (t: string, xs: { number: number; title: string; createdAt: string }[]) =>
  xs.slice().reverse().map((x) => `  - ${t} #${x.number} (${day(x.createdAt)}) ${x.title.replaceAll("|", "/")}`);
const md = ["# Upstream activity", "", "Generated by `bun tools/watch.ts`; newest open issues, PRs and discussions per upstream.", ""];
for (const r of up) {
  md.push(`- **${r.nameWithOwner}**: ${r.issues.totalCount} issues, ${r.pullRequests.totalCount} PRs, ${r.discussions.totalCount} discussions, ${r.forkCount} forks, release ${r.latestRelease?.tagName ?? "-"}`);
  md.push(...items("issue", r.ri.nodes), ...items("PR", r.rp.nodes), ...items("discussion", r.rd.nodes));
}
writeFileSync(join(out, "latest.md"), md.join("\n") + "\n");
console.log(JSON.stringify({ upstreams: up.length, microsoft: ms.length }));
